"""
pipeline/llm/prompt.py —— profile 分档讲解模板 (不讲 / 简讲 / 深讲)

1.3 的机制: "按需 vs 分级"是同一个策略函数的两个返回档。
explain_strategy: 'none' → 不生成讲解; 'brief' → 简讲; 'deep' → 深讲。

K33 (2026-08-16, 用户实测反馈"讲解字数是不是有点过分"后拍板"分档不够, 要能调字数和
触发门槛"): 之前 EXPLAIN_DEEP 写的是"讲得啰嗦一点没关系", 模型照做——实测 Wonder
一书讲解中位数 512 字符(原文的 10.7 倍), 逐句人工核对内容构成发现约 93% 是开场白/
复述常识/总结陈词/记忆口诀, 真正解释英语的部分只占约 7%。这次改动两件事:
  1. 提示词本身去掉"啰嗦"这类无约束描述, 换成明确禁止这几类跑题内容。
  2. explain_system_for 新增 max_chars 参数, 由 profile.explain_max_chars 传入,
     动态拼一条字数上限指令(不再是提示词里的固定文案)。
"""
from __future__ import annotations

# 讲解的分类清单 (2026-08-18): 原来只写"只解释查词典查不出来的东西(生词/搭配/结构)",
# 太笼统, 模型在没难点的句子上会凑废话 —— 实测短句讲解里大量是"said 是动词"
# "safe 是形容词"这种词性说明。给明确的六类 + 明确的排除项之后, 讲解明显更聚焦:
# 实测同一批句子非空讲解中位 60→49 字, 且抓的是真正的点(反义疑问句 right?、
# 过去完成时的参照点), 而不是基础词释义。
#
# 试过但**证伪**的一条: 给模型"没什么可讲就返回空字符串"的出口 —— 20 句实测
# **0 次**被用, 模型宁愿凑一条更没用的(如把人名解释成"此处为名字, 无其他含义")。
# 所以没有加这条指令; 要过滤没价值的短句讲解, 用 profile 的 explain_min_sentence_chars
# 门槛(见 K33), 那是调用方的取舍, 不是提示词能解决的。
EXPLAIN_BRIEF = (
    "你是英语老师的讲解助手。"
    "对每个句子输出 JSON: {{\"translation\": 中文翻译, "
    "\"explanation\": 中文讲解}}。\n"
    "讲解要求: 只讲真难的, 直接点破核心语法点或固定搭配, 直接说语法术语。\n"
    "**只讲下面这几类里这句话真正出现的东西**(按重要性排序, 讲到就够, 不必凑齐):\n"
    "1 生词难词: 读者可能不认识的实词; "
    "2 固定搭配/习语/俚语: 拆开每个词都认识但整体另有意思的; "
    "3 句子结构: 从句关系、非谓语、倒装、省略、后置修饰; "
    "4 时态语态: 只在它承载额外含义时才讲(如过去完成时表明更早发生), 不讲\"过去式表示过去\"; "
    "5 指代: it/they/this 具体指什么(长句里容易丢); "
    "6 口语拼写/缩写: doin'、ain't、gonna 这类。\n"
    "**不要写**: 基础词的词性说明(如\"said 是动词\" \"safe 是形容词\")、"
    "\"这句没有复杂结构\"这类自我说明、读者已知的常识、开场白、总结句、记忆口诀。\n"
    "输出必须是一个合法 JSON 对象(不是数组), 不要复述原文。"
)

EXPLAIN_DEEP = (
    "你是小学英语老师的讲解助手。"
    "对每个句子输出 JSON: {{\"translation\": 中文翻译, "
    "\"explanation\": 中文讲解}}。\n"
    "讲解要求: 站在小学生能懂的角度, 可以打比方帮孩子理解。\n"
    "**只讲下面这几类里这句话真正出现的东西**(按重要性排序, 讲到就够, 不必凑齐):\n"
    "1 生词难词: 读者可能不认识的实词; "
    "2 固定搭配/习语/俚语: 拆开每个词都认识但整体另有意思的; "
    "3 句子结构: 从句关系、非谓语、倒装、省略、后置修饰; "
    "4 时态语态: 只在它承载额外含义时才讲(如过去完成时表明更早发生), 不讲\"过去式表示过去\"; "
    "5 指代: it/they/this 具体指什么(长句里容易丢); "
    "6 口语拼写/缩写: doin'、ain't、gonna 这类。\n"
    "**不要写**: 基础词的词性说明(如\"said 是动词\" \"safe 是形容词\")、"
    "\"这句没有复杂结构\"这类自我说明、孩子本来就懂的常识(比如不用解释\"什么是风\")、"
    "开场白(比如\"好呀我们来想象一下\")、总结句、记忆口诀。\n"
    "输出必须是一个合法 JSON 对象(不是数组), 不要复述原文。"
)

EXPLAIN_NONE = None  # 不生成讲解


def explain_system_for(strategy: str, persona: str = "", max_chars: int | None = None) -> str | None:
    """max_chars: profile.explain_max_chars, 拼进提示词做明确字数约束
    (None/0 = 不额外约束, 兼容旧行为)。"""
    if strategy == "none":
        return None
    base = EXPLAIN_DEEP if strategy == "deep" else EXPLAIN_BRIEF
    if max_chars:
        # 2026-08-18: 原来这里写死"只讲最关键的一两点", 对复杂长句是硬性压制。
        # 实测 14454 句(Holes+Wonder+Hatchet): 原文从 40 字符长到 200+ 字符(5 倍),
        # 讲解中位只从 50 涨到 67 就饱和, 且全体仅 0.1% 超过 130 字 —— **max_chars 这个
        # 上限根本没在起作用, 真正卡住长度的是这句指令**。后果是多从句/多时态/转折让步的
        # 长句, 跟简单短句一样只得到"列两个生词"级别的讲解。改成按难度自适应。
        # A/B 实测(4 个 142-221 字符的真实长句): 讲解 69→123 / 107→103 / 110→125 /
        # 55→116 字, 3/4 明显变长且多出的是结构分析(时态/从句/后置修饰)不是废话;
        # 有一句基本没变, 说明不是无脑加长。
        base = (
            f"{base}\n讲解长度按句子难度自适应: 简单句一两点讲完即可(30-60 字); "
            "句子结构复杂时(多个从句、多种时态、转折让步)先点出主干, 再逐个交代从句/时态"
            "在句中承担什么关系。\n"
            f"讲解总字数控制在 {max_chars} 字以内, 不要为了凑字数展开背景或复述剧情。"
        )
    return base
